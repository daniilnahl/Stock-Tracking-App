// Only the reviewed M7 subset is supported. New schema keywords fail closed.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../tests/fixtures/api_foundation_openapi.json", import.meta.url);
const output = new URL("../src/services/contracts.generated.ts", import.meta.url);
const text = readFileSync(source, "utf8").replace(/\r\n/g, "\n");
const document = JSON.parse(text, (key, value, context) =>
  typeof value === "number" && ["minimum", "maximum"].includes(key) ? context.source : value);
const schemas = document.components.schemas;
const annotations = new Set(["title", "description", "examples"]);
const keywords = new Set(["$ref", "type", "anyOf", "properties", "required", "additionalProperties", "items", "pattern", "enum", "const", "minimum", "maximum"]);
function normalize(schema) {
  const result = {};
  for (const [key, value] of Object.entries(schema)) {
    if (annotations.has(key)) continue;
    if (!keywords.has(key)) throw new Error(`Unsupported schema keyword: ${key}`);
    if (key === "properties") result[key] = Object.fromEntries(Object.entries(value).map(([name, child]) => [name, normalize(child)]));
    else if (key === "anyOf") result[key] = value.map(normalize);
    else if (key === "items") result[key] = normalize(value);
    else result[key] = value;
  }
  return result;
}
function type(schema) {
  if (schema.$ref) {
    const name = schema.$ref.replace("#/components/schemas/", "");
    if (!(name in schemas) || schema.$ref !== `#/components/schemas/${name}`) throw new Error("Unsupported reference");
    return name;
  }
  if (schema.anyOf) return `(${schema.anyOf.map(type).join(" | ")})`;
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(" | ");
  if (schema.type === "integer") return schema.maximum && BigInt(schema.maximum) > BigInt(Number.MAX_SAFE_INTEGER) ? "bigint" : "number";
  if (schema.type === "string") return "string";
  if (schema.type === "null") return "null";
  if (schema.type === "array") return `ReadonlyArray<${type(schema.items)}>`;
  if (schema.type === "object") {
    if (schema.additionalProperties !== false || !schema.properties) throw new Error("Open object unsupported");
    return `{\n${Object.entries(schema.properties).map(([name, child]) => `  readonly ${JSON.stringify(name)}${schema.required?.includes(name) ? "" : "?"}: ${type(child)};`).join("\n")}\n}`;
  }
  throw new Error("Unsupported schema type");
}
const normalized = Object.fromEntries(Object.entries(schemas).map(([name, schema]) => [name, normalize(schema)]));
const errors = {};
for (const path of Object.values(document.paths)) {
  for (const operation of Object.values(path)) {
    for (const [status, response] of Object.entries(operation.responses ?? {})) {
      if (Number(status) < 400) continue;
      for (const example of Object.values(response.content?.["application/json"]?.examples ?? {})) {
        const { code, message } = example.value.error;
        const existing = errors[code];
        if (existing && JSON.stringify(existing) !== JSON.stringify([Number(status), message])) throw new Error("Inconsistent error contract");
        errors[code] = [Number(status), message];
      }
    }
  }
}
const generated = `// Generated by scripts/generate-contracts.mjs. Do not edit.\n// Source SHA-256: ${createHash("sha256").update(text).digest("hex")}\n\n` +
  Object.entries(normalized).map(([name, schema]) => `export type ${name} = ${type(schema)};\n`).join("\n") +
  `\nexport type Contracts = {\n${Object.keys(normalized).map(name => `  ${name}: ${name};`).join("\n")}\n};\n` +
  `\nexport const schemas = ${JSON.stringify(normalized, null, 2)} as const;\n` +
  `\nexport const errorContracts = ${JSON.stringify(errors, null, 2)} as const;\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8").replace(/\r\n/g, "\n") !== generated) throw new Error("M7 generated contracts are stale. Run npm run generate and review the schema diff.");
} else writeFileSync(output, generated);
