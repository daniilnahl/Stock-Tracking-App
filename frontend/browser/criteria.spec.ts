import { expect, test } from "@playwright/test";
for (const scenario of [{ theme: "light", width: 1440 }, { theme: "dark", width: 320 }] as const) {
  test(`custom criteria ${scenario.theme} at ${scenario.width}px stays local and keyboard accessible`, async ({ page }, info) => {
    await page.setViewportSize({ width: scenario.width, height: 1000 });
    await page.addInitScript(theme => localStorage.setItem("stock-tracker.theme", theme), scenario.theme);
    const requests: string[] = [];
    page.on("request", request => { requests.push(request.url()); });
    await page.goto("/");
    await page.getByRole("link", { name: "Open Stock criteria", exact: true }).focus();
    await page.keyboard.press("Enter");
    await expect(page.getByRole("heading", { name: "Stock criteria", exact: true })).toBeFocused();
    await page.waitForLoadState("networkidle");
    requests.length = 0;
    await page.getByRole("button", { name: "Prepare criteria", exact: true }).click();
    await expect(page.getByLabel("Parameter name 1", { exact: true })).toBeFocused();
    await expect(page.getByLabel("Parameter name 1", { exact: true })).toHaveAttribute("aria-invalid", "true");
    await page.getByLabel("Parameter name 1", { exact: true }).fill("My custom EPS request");
    await page.getByLabel("Units and context 1", { exact: true }).fill("User period and units, basis unresolved");
    await page.getByLabel("Minimum 1 (inclusive)", { exact: true }).fill("-0.000");
    await page.getByLabel("Maximum 1 (inclusive)", { exact: true }).fill("1.250000000000000001");
    await page.getByRole("button", { name: "Add criterion", exact: true }).click();
    await expect(page.getByLabel("Parameter name 2", { exact: true })).toBeFocused();
    await page.getByLabel("Parameter name 2", { exact: true }).fill("__proto__");
    await page.getByLabel("Criterion type 2", { exact: true }).selectOption("text");
    await page.getByLabel("Text requirement 2", { exact: true }).fill("<img src=x onerror=alert(1)> user text");
    await page.getByLabel("Match mode", { exact: true }).selectOption("any");
    await page.getByRole("button", { name: "Prepare criteria", exact: true }).focus();
    await page.keyboard.press("Enter");
    await expect(page.getByRole("heading", { name: "Prepared — Taurus search unavailable", exact: true })).toBeVisible();
    const preview = page.getByLabel("Prepared criteria snapshot", { exact: true });
    const original = await preview.textContent();
    expect(JSON.parse(original!).criteria[0].maximum).toBe("1.250000000000000001");
    await expect(page.locator("main img")).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await expect(page.locator("html")).toHaveAttribute("data-theme", scenario.theme);
    await page.evaluate(() => { const label = document.createElement("p"); label.className = "demo-label"; label.textContent = "Synthetic custom criteria / no search / no live data"; document.querySelector("main h1")?.after(label); });
    await page.screenshot({ path: info.outputPath(`criteria-${scenario.theme}-${scenario.width}.png`), fullPage: true });
    await page.getByRole("link", { name: "Overview", exact: true }).click();
    await expect(page.getByText("Placeholder / unavailable", { exact: true })).toHaveCount(2);
    await page.getByRole("link", { name: "Stock criteria", exact: true }).click();
    await expect(preview).toHaveText(original!);
    await page.getByLabel("Maximum 1 (inclusive)", { exact: true }).fill("9");
    await expect(page.getByLabel("Outdated criteria snapshot", { exact: true })).toHaveText(original!);
    await page.getByRole("button", { name: "Remove criterion 2", exact: true }).click();
    await expect(page.getByLabel("Parameter name 1", { exact: true })).toBeFocused();
    expect(requests).toEqual([]);
    expect(await page.evaluate(() => Object.keys(localStorage))).toEqual(["stock-tracker.theme"]);
    expect(await page.evaluate(() => Object.keys(sessionStorage))).toEqual([]);
    await page.reload();
    await expect(page.getByLabel("Parameter name 1", { exact: true })).toHaveValue("");
    await expect(page.getByLabel("Prepared criteria snapshot", { exact: true })).toHaveCount(0);
    await page.getByLabel("Parameter name 1", { exact: true }).fill("clear me");
    await page.getByRole("button", { name: "Clear criteria", exact: true }).click();
    await expect(page.getByLabel("Parameter name 1", { exact: true })).toHaveValue("");
    await expect(page.getByLabel("Parameter name 1", { exact: true })).toBeFocused();
  });
}
